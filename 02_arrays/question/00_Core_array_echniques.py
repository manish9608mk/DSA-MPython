'''
Core Array Techniques:

|    | Technique / Pattern    | Typical use                           |
| -- | ---------------------- | ------------------------------------- |
| 1  | Traversal              | Visit/process every element           |
| 2  | Two Pointers           | Pair problems, in-place modification  |
| 3  | Sliding Window         | Subarray/contiguous range             |
| 4  | Prefix Sum             | Fast range-sum/subarray calculations  |
| 5  | Hashing                | Frequency, lookup, duplicates         |
| 6  | Binary Search          | Search in sorted/monotonic data       |
| 7  | Sorting                | Organize data to simplify the problem |
| 8  | Kadane's Algorithm     | Maximum subarray sum                  |
| 9  | Difference Array       | Efficient range updates               |
| 10 | Monotonic Stack        | Next greater/smaller problems         |
| 11 | Heap / Priority Queue  | Top-K, min/max elements               |
| 12 | Greedy                 | Make locally optimal choices          |
| 13 | Divide & Conquer       | Split array into smaller problems     |
| 14 | Binary Search on Answer| Optimize a minimum/maximum value      |
| 15 | Backtracking           | Generate combinations/permutations    |
| 16 | Dynamic Programming    | Optimization/counting subproblems     |

Note:
So when solving an array problem, don't ask:
"Which algorithm should I memorize?"

Ask:
"What pattern does this problem indicate?"

That's the skill you want to build for interviews.
'''